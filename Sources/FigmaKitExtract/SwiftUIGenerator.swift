import Foundation

/// Stage 3: tokens to Swift source. The output has two layers:
/// plain value types (compile anywhere, easy to diff and unit-test) and a
/// SwiftUI layer behind `#if canImport(SwiftUI)` that stacks the fills as
/// separate shape layers, which is the whole point of reading the kit.
public struct SwiftUIGenerator {
    public var namespace: String
    public var header: String?
    public init(namespace: String = "Kit", header: String? = nil) {
        self.namespace = Self.typeIdentifier(namespace)
        self.header = header
    }

    public func generate(_ tokens: [ComponentToken]) -> String {
        var out = "// Generated by adt-figma. Do not edit by hand.\n"
        if let header { out += header.split(separator: "\n").map { "// " + $0 }.joined(separator: "\n") + "\n" }
        out += "\n" + Self.runtime + "\n"
        out += "public enum \(namespace) {\n"
        var used = Set<String>()
        for t in tokens {
            let id = Self.unique(Self.typeIdentifier(t.name + " " + Self.variantSuffix(t.variant)), &used)
            out += "    /// \(Self.docName(t))\n"
            out += "    public static let \(Self.lowerFirst(id)): KitComponentSpec = \(spec(t, indent: 2))\n"
        }
        out += "}\n"
        return out
    }

    func spec(_ t: ComponentToken, indent: Int) -> String {
        let p = String(repeating: "    ", count: indent)
        var s = "KitComponentSpec(\n"
        s += "\(p)name: \(Self.literal(t.name)),\n"
        s += "\(p)width: \(Self.num(t.width)), height: \(Self.num(t.height)),\n"
        s += "\(p)shape: \(shape(t.shape)),\n"
        s += "\(p)fills: [\(t.fills.map { rgba($0.color) }.joined(separator: ", "))],\n"
        s += "\(p)stroke: \(t.stroke.map { rgba($0.color) } ?? "nil"), strokeWidth: \(Self.num(t.strokeWidth)),\n"
        s += "\(p)shadows: [\(t.shadows.map(shadow).joined(separator: ", "))],\n"
        s += "\(p)backgroundBlur: \(t.backgroundBlur.map(Self.num) ?? "nil"),\n"
        if t.parts.isEmpty {
            s += "\(p)parts: [:]\n"
        } else {
            s += "\(p)parts: [\n"
            var used = Set<String>()
            for part in t.parts {
                let key = Self.unique(Self.lowerFirst(Self.typeIdentifier(part.name)), &used)
                s += "\(p)    \(Self.literal(key)): \(spec(part, indent: indent + 2)),\n"
            }
            s += "\(p)]\n"
        }
        return s + String(repeating: "    ", count: indent - 1) + ")"
    }

    func rgba(_ c: RGBA) -> String {
        "KitRGBA(\(Self.num(c.r)), \(Self.num(c.g)), \(Self.num(c.b)), \(Self.num(c.a)))"
    }
    func shadow(_ s: ComponentToken.Shadow) -> String {
        "KitShadow(inner: \(s.inner), color: \(rgba(s.color)), radius: \(Self.num(s.radius)), x: \(Self.num(s.x)), y: \(Self.num(s.y)))"
    }
    func shape(_ s: ComponentToken.Shape) -> String {
        switch s {
        case .rectangle: return ".rectangle"
        case .capsule: return ".capsule"
        case .rounded(let r): return ".rounded(\(Self.num(r)))"
        case .corners(let v): return ".corners(\(v.map(Self.num).joined(separator: ", ")))"
        }
    }

    // MARK: identifiers and literals

    static let keywords: Set<String> = [
        "associatedtype", "class", "deinit", "enum", "extension", "func", "import", "init", "inout", "let",
        "operator", "protocol", "static", "struct", "subscript", "typealias", "var", "break", "case",
        "continue", "default", "defer", "do", "else", "fallthrough", "for", "guard", "if", "in", "repeat",
        "return", "switch", "where", "while", "as", "catch", "false", "is", "nil", "rethrows", "super",
        "self", "Self", "throw", "throws", "true", "try", "Any", "Type", "internal", "private", "public",
    ]

    /// "Toggles / Switches", "Mode=Dark" -> "TogglesSwitchesModeDark".
    public static func typeIdentifier(_ s: String) -> String {
        var words: [String] = [], cur = ""
        for ch in s {
            if ch.isASCII, ch.isLetter || ch.isNumber { cur.append(ch) }
            else if !cur.isEmpty { words.append(cur); cur = "" }
        }
        if !cur.isEmpty { words.append(cur) }
        var id = words.map { $0.prefix(1).uppercased() + $0.dropFirst() }.joined()
        if id.isEmpty { id = "Unnamed" }
        if id.first!.isNumber { id = "_" + id }
        return keywords.contains(id) ? "`\(id)`" : id
    }

    static func lowerFirst(_ s: String) -> String {
        if s.hasPrefix("`") || s.hasPrefix("_") { return s }
        var r = s
        let lead = r.prefix(while: { $0.isUppercase })
        // "URLField" -> "urlField", "Button" -> "button"
        let n = lead.count > 1 && lead.count < r.count ? lead.count - 1 : lead.count
        r = r.prefix(n).lowercased() + r.dropFirst(n)
        return keywords.contains(r) ? "`\(r)`" : r
    }

    static func unique(_ id: String, _ used: inout Set<String>) -> String {
        var cand = id, i = 2
        while used.contains(cand) { cand = id + String(i); i += 1 }
        used.insert(cand)
        return cand
    }

    static func variantSuffix(_ v: [String: String]) -> String {
        v.keys.sorted().map { "\($0) \(v[$0]!)" }.joined(separator: " ")
    }

    static func docName(_ t: ComponentToken) -> String {
        let base = t.name.replacingOccurrences(of: "\n", with: " ")
        return t.variant.isEmpty ? base : base + " (" + t.variant.keys.sorted().map { "\($0)=\(t.variant[$0]!)" }.joined(separator: ", ") + ")"
    }

    static func literal(_ s: String) -> String {
        var r = "\""
        for u in s.unicodeScalars {
            switch u {
            case "\\": r += "\\\\"
            case "\"": r += "\\\""
            case "\n": r += "\\n"
            case "\r": r += "\\r"
            case "\t": r += "\\t"
            default:
                if u.value < 0x20 { r += "\\u{\(String(u.value, radix: 16))}" } else { r.unicodeScalars.append(u) }
            }
        }
        return r + "\""
    }

    /// Up to 4 decimals, no exponent, no trailing zeros: 0.0200 -> 0.02, 54.0 -> 54.
    public static func num(_ d: Double) -> String {
        var s = String(format: "%.4f", d)
        while s.hasSuffix("0") { s.removeLast() }
        if s.hasSuffix(".") { s.removeLast() }
        return s == "-0" ? "0" : s
    }

    static let runtime = #"""
    public struct KitRGBA: Equatable {
        public let r: Double, g: Double, b: Double, a: Double
        public init(_ r: Double, _ g: Double, _ b: Double, _ a: Double) { self.r = r; self.g = g; self.b = b; self.a = a }
    }

    public struct KitShadow: Equatable {
        public let inner: Bool, color: KitRGBA, radius: Double, x: Double, y: Double
    }

    public enum KitShape: Equatable {
        case rectangle, capsule
        case rounded(Double)
        /// topLeading, topTrailing, bottomTrailing, bottomLeading
        case corners(Double, Double, Double, Double)
    }

    public struct KitComponentSpec: Equatable {
        public let name: String
        public let width: Double, height: Double
        public let shape: KitShape
        /// Bottom to top. Stack them; never average.
        public let fills: [KitRGBA]
        public let stroke: KitRGBA?, strokeWidth: Double
        public let shadows: [KitShadow]
        public let backgroundBlur: Double?
        public let parts: [String: KitComponentSpec]
    }

    #if canImport(SwiftUI)
    import SwiftUI

    public extension KitRGBA {
        var color: Color { Color(.sRGB, red: r, green: g, blue: b, opacity: a) }
    }

    public extension KitShape {
        var shape: AnyShape {
            switch self {
            case .rectangle: return AnyShape(Rectangle())
            case .capsule: return AnyShape(Capsule(style: .continuous))
            case .rounded(let r): return AnyShape(RoundedRectangle(cornerRadius: r, style: .continuous))
            case let .corners(tl, tr, br, bl):
                if #available(macOS 14, iOS 17, *) {
                    return AnyShape(UnevenRoundedRectangle(topLeadingRadius: tl, bottomLeadingRadius: bl,
                                                           bottomTrailingRadius: br, topTrailingRadius: tr,
                                                           style: .continuous))
                }
                return AnyShape(RoundedRectangle(cornerRadius: max(tl, tr, br, bl), style: .continuous))
            }
        }
    }

    /// The surface of a kit component: each fill is its own layer, drop
    /// shadows outside, inner shadows (specular edges) on the top layer.
    /// Figma blur radius is a CSS-style blur; SwiftUI's radius is roughly half.
    public struct KitSurface: View {
        public let spec: KitComponentSpec
        public init(_ spec: KitComponentSpec) { self.spec = spec }
        public var body: some View {
            let shape = spec.shape.shape
            return ZStack {
                ForEach(Array(spec.fills.enumerated()), id: \.offset) { i, f in
                    if i == spec.fills.count - 1 {
                        shape.fill(spec.shadows.filter(\.inner).reduce(AnyShapeStyle(f.color)) { style, s in
                            AnyShapeStyle(style.shadow(.inner(color: s.color.color, radius: s.radius / 2, x: s.x, y: s.y)))
                        })
                    } else {
                        shape.fill(f.color)
                    }
                }
                if let stroke = spec.stroke {
                    shape.stroke(stroke.color, lineWidth: spec.strokeWidth)
                }
            }
            .frame(width: spec.width, height: spec.height)
            .modifier(KitDropShadows(shadows: spec.shadows.filter { !$0.inner }))
        }
    }

    struct KitDropShadows: ViewModifier {
        let shadows: [KitShadow]
        func body(content: Content) -> some View {
            shadows.reduce(AnyView(content)) { v, s in
                AnyView(v.shadow(color: s.color.color, radius: s.radius / 2, x: s.x, y: s.y))
            }
        }
    }
    #endif
    """#
}
