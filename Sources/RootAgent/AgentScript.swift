import Foundation
import ToolkitCore

/// Generates the root-owned agent.sh. Every verb's executable and arguments
/// are baked in at generation time; the request only selects which case runs.
public struct AgentScript {
    public var appName: String
    public var supportDir: String
    public var registry: CommandRegistry
    public var logTag: String

    public init(appName: String, supportDir: String? = nil, registry: CommandRegistry) {
        try! Identifier.validatePathComponent(appName, field: "appName")
        self.appName = appName
        self.supportDir = supportDir ?? "/Library/Application Support/\(appName)"
        self.registry = registry
        self.logTag = appName.lowercased().replacingOccurrences(of: " ", with: "-")
    }

    public var spoolDir: String { supportDir + "/spool" }
    public var reportsDir: String { supportDir + "/reports" }
    public var agentPath: String { supportDir + "/agent.sh" }

    public func render() -> String {
        var cases = ""
        for cmd in registry.commands {
            cases += "  \(cmd.verb))\n"
            switch cmd.output {
            case .ok:
                cases += "    \(Shell.join([cmd.executable] + cmd.arguments)) >/dev/null 2>&1\n"
                cases += "    printf 'ok\\n' > \"$REPLY\"\n"
            case .report(let dir, let prefix):
                cases += "    OUT=\(Shell.quote(dir))/\(Shell.quote(prefix))-$(date +%Y%m%d-%H%M%S).txt\n"
                cases += "    mkdir -p \(Shell.quote(dir))\n"
                cases += "    \(Shell.join([cmd.executable] + cmd.arguments)) >\"$OUT\" 2>&1\n"
                cases += "    printf '%s\\n' \"$OUT\" > \"$REPLY\"\n"
            }
            cases += "    chmod 644 \"$REPLY\"\n"
            cases += "    ;;\n"
        }
        return """
        #!/bin/bash
        # Generated by AppleDesignToolkit RootAgent. Do not edit.
        # Owned root:wheel, mode 755. Root must never execute a user-writable file.
        set -eu
        SPOOL=\(Shell.quote(spoolDir))
        LOG=/var/log/\(Shell.quote(logTag))-agent.log
        log() { printf '%s %s\\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$*" >>"$LOG" 2>/dev/null || true; }

        # Sweep stale replies (skill: find -mmin +5 -delete).
        find "$SPOOL" -maxdepth 1 -type f -name 'done-*' -mmin +5 -delete 2>/dev/null || true

        shopt -s nullglob
        for req in "$SPOOL"/req-*; do
          [ -f "$req" ] || continue
          base=$(basename "$req")
          id=${base#req-}
          id="${id//[^a-zA-Z0-9]/}"
          if [ -z "$id" ]; then
            rm -f "$req"
            log "ignored request with empty id"
            continue
          fi
          REPLY="$SPOOL/done-$id"
          verb=$(head -1 "$req" | tr -cd 'a-z')
          rm -f "$req"
          case "$verb" in
        \(cases)\
          *)
            log "ignored unknown request verb=$verb"
            ;;
          esac
        done
        """
    }
}
